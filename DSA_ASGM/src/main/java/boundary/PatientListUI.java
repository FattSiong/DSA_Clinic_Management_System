    private void populateTable() {
        // Get the JTable's model to be able to add rows to it
        DefaultTableModel model = (DefaultTableModel) tblPatient.getModel();
        // Clear any existing rows from the table before adding new ones
        model.setRowCount(0);

        // Get the list of patients from the control class
        ListInterface<Patient> patientList = patientControl.getPatientList();

        // Use an iterator to loop through the patient list
        Iterator<Patient> iterator = patientList.getIterator();
        while (iterator.hasNext()) {
            Patient patient = iterator.next();
            
            // Create an array of objects for the row data
            Object[] rowData = {
                patient.getPatientID(),
                patient.getName(),
                patient.getGender(),
                patient.getAge(),
                patient.getIcNumber(),
                patient.getContactNumber(),
                patient.getEmail(),
                patient.getMedicalHistory()
            };
            
            // Add the new row to the table model
            model.addRow(rowData);
        }
    }
    
